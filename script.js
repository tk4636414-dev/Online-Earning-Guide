async function saveArticleToFirestore(
    article
) {   

    if (!db) {

        throw new Error(
            "Firestore initialize نہیں ہوا۔"
        );

    }

    if (!article) {

        throw new Error(
            "Article data is required."
        );

    }

    const articleData = {

        title:
            article.title || "",

        description:
            article.description || "",

        content:
            article.content || "",

        category:
            article.category || "",

        imageUrl:
            article.imageUrl || "",

        authorUid:
            currentUser
                ? currentUser.uid
                : null,

        authorEmail:
            currentUser
                ? currentUser.email
                : null,

        updatedAt:
            serverTimestamp()

    };

    // Existing article
    if (article.id) {

        const articleRef =
            doc(
                db,
                ARTICLE_COLLECTION,
                String(article.id)
            );

        await setDoc(
            articleRef,
            {
                ...articleData,

                ...(article.createdAt
                    ? {
                        createdAt:
                            article.createdAt
                    }
                    : {
                        createdAt:
                            serverTimestamp()
                    })

            },
            {
                merge:
                    true
            }
        );

        await renderArticles();

        return String(
            article.id
        );

    }

    // New article
    const articleRef =
        await addDoc(
            collection(
                db,
                ARTICLE_COLLECTION
            ),
            {
                ...articleData,

                createdAt:
                    serverTimestamp()
            }
        );

    await renderArticles();

    renderLocalArticles();

    return articleRef.id;

}


