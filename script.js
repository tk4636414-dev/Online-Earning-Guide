// TEXT TO SPEECH
// ============================================================

async function readArticleAudio() {
    if (audioGenerationInProgress) return;
    audioGenerationInProgress = true;

    const title = getElement("modalTitle");
    const body = getElement("modalBody");
    const audioBtn = getElement("audioPlayBtn");

    try {
        const accessUser = await requireFeatureAccess(
            "آڈیو سننے کے لیے پہلے Google سے لاگ ان کریں۔"
        );
        if (!accessUser || !title || !body) return;

        const text = cleanSpeechText(`${title.textContent}. ${body.innerText}`);
        if (!text) throw new Error("آڈیو کے لیے متن موجود نہیں ہے۔");

        stopArticleAudio();
        if (audioBtn) {
            audioBtn.disabled = true;
            audioBtn.classList.add("audio-loading");
            audioBtn.textContent = "⏳ آڈیو جنریٹ ہو رہی ہے...";
        }

        const response = await fetch("/api/text-to-speech", {
            method: "POST",
            headers: {
                "Content-Type": "application/json",
                Authorization: `Bearer ${await accessUser.getIdToken()}`
            },
            body: JSON.stringify({ text })
        });

        if (!response.ok) {
            const errorData = await response.json().catch(() => ({}));
            throw new Error(errorData.error || "Audio generation failed.");
        }

        const blob = await response.blob();
        currentAudioUrl = URL.createObjectURL(blob);
        const audio = new Audio(currentAudioUrl);
        currentAudioElement = audio;
        audio.volume = 1;

        audio.onplay = () => {
            updateAudioPlaybackControls(true, true, "Playing");
            if (audioBtn) audioBtn.textContent = "🔊 آڈیو چل رہی ہے";
        };
        audio.onpause = () => {
            if (currentAudioElement === audio && !audio.ended) {
                updateAudioPlaybackControls(true, false, "Paused");
                if (audioBtn) audioBtn.textContent = "▶ آڈیو جاری رکھیں";
            }
        };
        audio.onended = () => {
            updateAudioPlaybackControls(true, false, "Finished. Press Play to listen again.");
            resetAudioButton(audioBtn);
        };
        audio.onerror = () => {
            updateAudioPlaybackControls(true, false, "Audio playback failed. Press Play to retry.");
            resetAudioButton(audioBtn);
        };

        updateAudioPlaybackControls(true, false, "Audio ready");
        await audio.play();
        if (audioBtn) {
            audioBtn.disabled = false;
            audioBtn.classList.remove("audio-loading");
        }
    } catch (error) {
        console.error("TTS error:", {
            name: error.name || "Error",
            message: error.message || "Audio generation failed."
        });
        resetAudioButton(audioBtn);
        if (currentAudioElement) {
            updateAudioPlaybackControls(true, false, error.message || "Audio playback failed.");
        } else {
            updateAudioPlaybackControls(false, false, "");
            alert(`آڈیو پلے کرنے میں مسئلہ پیش آیا۔\n${error.message || ""}`);
        }
    } finally {
        audioGenerationInProgress = false;
    }
}


