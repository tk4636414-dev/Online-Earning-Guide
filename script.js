function setupSubscriptionEvents() {

    const modal =
        getElement("subscription-modal");

    const closeButton =
        getElement("subscription-close-btn");

    const checkoutButtons =
        document.querySelectorAll(
            ".card-pay-btn"
        );

    const manualPaymentForm =
        getElement("manual-payment-form");

    if (!modal) return;

    manualPaymentForm?.addEventListener(
        "submit",
        submitManualPayment
    );

    closeButton?.addEventListener(
        "click",
        closeUpgradeModal
    );

    checkoutButtons.forEach(
        checkoutButton => {

            checkoutButton.addEventListener(
                "click",
                async event => {

                    event.preventDefault();
                    if (checkoutButton.dataset.loading === "true") return;
                    checkoutButton.dataset.loading = "true";
                    const status = getElement("payment-status");
                    checkoutButton.setAttribute("aria-disabled", "true");
                    checkoutButton.classList.add("is-loading");

                    try {
                        let user = getCurrentUser();
                        if (!user) {
                            const result = await loginWithGoogle();
                            if (!result.success) {
                                if (!result.cancelled) {
                                    throw result.error || new Error("Checkout کے لیے پہلے Google سے لاگ ان کریں۔");
                                }
                                return;
                            }
                            user = result.user;
                        }

                        if (status) {
                            status.hidden = false;
                            status.textContent = "Secure checkout تیار کیا جا رہا ہے...";
                        }

                        const response = await fetch("/api/create-checkout", {
                            method: "POST",
                            headers: {
                                "Content-Type": "application/json",
                                Authorization: `Bearer ${await user.getIdToken(true)}`
                            },
                            body: JSON.stringify({ plan: checkoutButton.dataset.checkoutPlan })
                        });
                        const result = await response.json().catch(() => ({}));
                        if (!response.ok || typeof result.checkoutUrl !== "string") {
                            throw new Error(result.error || "Card checkout could not be started.");
                        }

                        window.location.assign(result.checkoutUrl);
                    } catch (error) {
                        console.error("Card checkout start failed:", {
                            message: error.message || "Checkout failed."
                        });
                        if (status) {
                            status.hidden = false;
                            status.textContent = error.message || "Card checkout could not be started.";
                        }
                    } finally {
                        delete checkoutButton.dataset.loading;
                        checkoutButton.removeAttribute("aria-disabled");
                        checkoutButton.classList.remove("is-loading");
                    }

                }
            );

        }
    );

    modal.addEventListener(
        "click",
        event => {

            if (event.target === modal) {

                closeUpgradeModal();

            }

        }
    );

}


function sanitizeArticleHTML(value) {

    const html =
        safeText(value);

    if (window.DOMPurify) {

        return window.DOMPurify.sanitize(
            html,
            {
                USE_PROFILES: {
                    html: true
                }
            }
        );

    }

    return escapeHTML(html);

}


function safeImageURL(value) {

    try {

        const url =
            new URL(
                safeText(value),
                window.location.origin
            );

        return [
            "http:",
            "https:"
        ].includes(url.protocol)
            ? url.href
            : "";

    } catch {

        return "";

    }

}


function setupMobileNavigation() {

    const toggle =
        getElement("menuToggle");

    const navigation =
        getElement("siteNavigation");

    if (!toggle || !navigation) return;

    const drawerClose =
        navigation.querySelector(".nav-drawer-close");

    const closeMenu =
        () => {

            navigation.classList.remove(
                "is-open"
            );

            toggle.setAttribute(
                "aria-expanded",
                "false"
            );

            toggle.setAttribute(
                "aria-label",
                "مینو کھولیں"
            );

        };

    toggle.addEventListener(
        "click",
        () => {

            const isOpen =
                navigation.classList.toggle(
                    "is-open"
                );

            toggle.setAttribute(
                "aria-expanded",
                String(isOpen)
            );

            toggle.setAttribute(
                "aria-label",
                isOpen
                    ? "مینو بند کریں"
                    : "مینو کھولیں"
            );

        }
    );

    drawerClose?.addEventListener(
        "click",
        closeMenu
    );

    navigation
        .querySelectorAll("a")
        .forEach(
            link => link.addEventListener(
                "click",
                closeMenu
            )
        );

    document.addEventListener(
        "click",
        event => {

            if (
                navigation.classList.contains("is-open") &&
                event.target === navigation
            ) {

                closeMenu();

            }

        }
    );

    document.addEventListener(
        "keydown",
        event => {

            if (
                event.key === "Escape" &&
                navigation.classList.contains("is-open")
            ) {

                closeMenu();

                toggle.focus();
            }

        }
    );

    window.addEventListener(
        "resize",
        () => {

            if (window.innerWidth > 1100) {
                closeMenu();
            }

        }
    );

}
