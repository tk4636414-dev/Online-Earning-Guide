// ============================================================
// Clean Speech Text
// ============================================================

function cleanSpeechText(text) {

    return safeText(text)

        .replace(
            /<[^>]*>/g,
            " "
        )

        .replace(
            /&nbsp;/gi,
            " "
        )

        .replace(
            /\b\d+\s*\.\s*/g,
            " "
        )

        .replace(
            /-\s*سٹیپ\s+\d+\s*[:.]/g,
            " "
        )

        .replace(
            /[\u200B-\u200D\uFEFF]/g,
            ""
        )

        .replace(
            /\s+/g,
            " "
        )

        .trim();

}


