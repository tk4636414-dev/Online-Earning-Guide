async function openModal(articleId, { updateHistory = true } = {}) {

    const modal =
        getElement("articleModal");

    const modalTitle =
        getElement("modalTitle");

    const modalBody =
        getElement("modalBody");


    if (
        !modal ||
        !modalTitle ||
        !modalBody
    ) {

        console.error(
            "Modal HTML elements missing ہیں."
        );

        return;
    }

    const requestedArticleId = String(articleId || "").trim();
    if (!requestedArticleId) return;

    if (updateHistory) {
        const url = new URL(window.location.href);
        if (url.searchParams.get("article") !== requestedArticleId) {
            url.searchParams.set("article", requestedArticleId);
            const currentState = window.history.state && typeof window.history.state === "object"
                ? window.history.state
                : {};
            window.history.pushState({
                ...currentState,
                articleModal: true,
                articleId: requestedArticleId
            }, "", url);
            articleModalHistoryPushed = true;
        }
    }


    // پہلے چلتی ہوئی audio بند کریں
    stopArticleAudio();


    // Modal open
    modal.style.display =
        "block";

    requestAnimationFrame(
        () => modal.classList.add(
            "is-visible"
        )
    );

    document.body.style.overflow =
        "hidden";


    // Loading
    modalTitle.textContent =
        "⏳ آرٹیکل لوڈ ہو رہا ہے...";

    modalBody.innerHTML = `
        <div class="article-loading">
            آرٹیکل کی مکمل تفصیل لوڈ ہو رہی ہے...
        </div>
    `;


    try {

        let article = null;


        // ====================================================
        // 1. پہلے merged realtime articles سے تلاش
        // ====================================================

        article =
            currentArticles.find(
                item =>
                    String(item.id) ===
                    requestedArticleId
            );


        // ====================================================
        // 2. اگر merged list میں نہ ملے
        //    تو Firebase سے تلاش کریں
        // ====================================================

        if (
            !article &&
            db
        ) {

            try {

                article =
                    await getArticleFromFirestore(
                        requestedArticleId
                    );

            } catch (firebaseError) {

                console.warn(
                    "Firebase article fetch failed:",
                    firebaseError
                );

            }

        }


        // ====================================================
        // 3. Article نہیں ملا
        // ====================================================

        if (!article) {

            modalTitle.textContent =
                "آرٹیکل نہیں ملا";

            modalBody.innerHTML = `
                <div class="articles-error">

                    ❌ یہ آرٹیکل موجود نہیں ہے۔

                </div>
            `;

            return;
        }


        // ====================================================
        // 4. Full Article Title
        // ====================================================

        modalTitle.textContent =
            article.title ||
            "بلا عنوان";


        // ====================================================
        // 5. Full Article Content
        // ====================================================

        modalBody.innerHTML =
            sanitizeArticleHTML(
                article.content ||
                article.description ||
                `
                    <p>
                        آرٹیکل کا مکمل مواد موجود نہیں ہے۔
                    </p>
                `
            );


        console.log(
            "✅ Full article opened:",
            article.title
        );


    } catch (error) {

        console.error(
            "Open article error:",
            error
        );


        modalTitle.textContent =
            "آرٹیکل";


        modalBody.innerHTML = `
            <div class="articles-error">

                ❌ آرٹیکل کھولنے میں مسئلہ پیش آیا۔

                <br><br>

                <small>
                    ${escapeHTML(
                        error.message ||
                        "Unknown error"
                    )}
                </small>

            </div>
        `;

    }

}
// ============================================================
// CLOSE MODAL
// ============================================================

function closeModal({ updateHistory = true } = {}) {

    if (updateHistory) {
        const url = new URL(window.location.href);
        if (url.searchParams.has("article")) {
            if (articleModalHistoryPushed) {
                articleModalHistoryPushed = false;
                window.history.back();
            } else {
                url.searchParams.delete("article");
                const currentState = window.history.state && typeof window.history.state === "object"
                    ? { ...window.history.state }
                    : {};
                delete currentState.articleModal;
                delete currentState.articleId;
                window.history.replaceState(currentState, "", url);
            }
        }
    }

    const modal =
        getElement("articleModal");

    if (modal) {

        modal.classList.remove(
            "is-visible"
        );

        window.setTimeout(
            () => {
                if (!modal.classList.contains("is-visible")) {
                    modal.style.display =
                        "none";
                }
            },
            220
        );

    }

    document.body.style.overflow =
        "auto";

    stopArticleAudio();

}


function handleArticleHistoryChange() {
    const articleId = new URL(window.location.href).searchParams.get("article");
    articleModalHistoryPushed = Boolean(window.history.state?.articleModal);

    if (articleId) {
        openModal(articleId, { updateHistory: false });
    } else {
        articleModalHistoryPushed = false;
        closeModal({ updateHistory: false });
    }
}


