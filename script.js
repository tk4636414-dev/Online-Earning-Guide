const ARTICLE_SCHEDULE_INTERVAL =
    12 * 60 * 60 * 1000;

let articleSchedulerTimer =
    null;


// ============================================================
// Start Scheduler
// ============================================================

function startArticleScheduler() {

    stopArticleScheduler();

    updateArticleSchedulerStatus();

    articleSchedulerTimer =
        setInterval(
            updateArticleSchedulerStatus,
            60 * 1000
        );

}


// ============================================================
// Stop Scheduler
// ============================================================

function stopArticleScheduler() {

    if (articleSchedulerTimer) {

        clearInterval(
            articleSchedulerTimer
        );

        articleSchedulerTimer =
            null;

    }

}


// ============================================================
// Scheduler Status
// ============================================================

function updateArticleSchedulerStatus() {

    const status =
        getElement(
            "articleSchedulerStatus"
        );

    if (!status) return;

    const lastGeneration =
        localStorage.getItem(
            "lastArticleGenerationTime"
        );

    if (!lastGeneration) {

        status.textContent =
            "اگلا آرٹیکل: سرور کے 12 گھنٹے والے شیڈول کے مطابق";

        return;

    }

    const lastTime =
        Number(
            lastGeneration
        );

    if (!Number.isFinite(lastTime)) {

        status.textContent =
            "اگلا آرٹیکل: سرور کے 12 گھنٹے والے شیڈول کے مطابق";

        return;

    }

    const nextTime =
        lastTime +
        ARTICLE_SCHEDULE_INTERVAL;

    const remaining =
        nextTime -
        Date.now();

    if (remaining <= 0) {

        status.textContent =
            "نیا آرٹیکل جنریٹ ہونے کے لیے تیار ہے۔";

        return;

    }

    const hours =
        Math.floor(
            remaining /
            (60 * 60 * 1000)
        );

    const minutes =
        Math.floor(
            (
                remaining %
                (60 * 60 * 1000)
            ) /
            (60 * 1000)
        );

    status.textContent =
        `اگلا آرٹیکل تقریباً ${hours} گھنٹے ${minutes} منٹ بعد`;

}


// ============================================================
// Mark Generation Time
// ============================================================

function markArticleGenerationTime() {

    localStorage.setItem(
        "lastArticleGenerationTime",
        String(
            Date.now()
        )
    );

    updateArticleSchedulerStatus();

}


