async function generateArticleNow() {

    try {

        const response =
            await fetch(
                "/api/generate-article",
                {
                    method:
                        "POST",

                    headers: {
                        "Content-Type":
                            "application/json",

                        ...(getCurrentUser()
                            ? {
                                "Authorization":
                                    `Bearer ${await getCurrentUser().getIdToken()}`
                            }
                            : {})
                    }
                }
            );

        let data =
            null;

        try {

            data =
                await response.json();

        } catch (error) {

            data =
                {};

        }

        if (!response.ok) {

            throw new Error(
                data?.error ||
                "Article generation failed."
            );

        }

        markArticleGenerationTime();

        // Newly generated article
        // immediately appears.
        await renderArticles();

        return {
            success: true,
            data
        };

    } catch (error) {

        console.error(
            "Generate article error:",
            error
        );

        return {
            success: false,
            error
        };

    }

}


